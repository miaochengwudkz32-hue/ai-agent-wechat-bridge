// End-to-end test: fake WeChat server + real bridge.js + real `claude -p` (cheap model).
// Usage: node test/e2e.mjs [--skip-screenshot]
import { spawn, execFile } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MOCK_PORT = 18799;
const WAKE_PORT = 18798;
const skipScreenshot = process.argv.includes("--skip-screenshot");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "claude-wechat-e2e-"));
const stateDir = path.join(tmp, "state");
fs.mkdirSync(stateDir, { recursive: true });
fs.writeFileSync(
  path.join(stateDir, "account.json"),
  JSON.stringify({ token: "test-token", botId: "bot@im.bot", baseUrl: `http://127.0.0.1:${MOCK_PORT}`, userId: "owner@im.wechat" }),
);
const configFile = path.join(tmp, "config.json");
fs.writeFileSync(configFile, JSON.stringify({ model: "haiku", wakePort: WAKE_PORT, schedules: [], addDirs: [tmp] }));
// test files
const filesDir = path.join(tmp, "files");
fs.mkdirSync(filesDir);
fs.writeFileSync(path.join(filesDir, "note.txt"), "这是一份测试笔记。\n第二行。\n", "utf-8");
fs.writeFileSync(path.join(filesDir, "other.md"), "# other\n", "utf-8");
const pngFile = path.join(tmp, "dot.png");
fs.writeFileSync(pngFile, Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==", "base64"));
// Separate workspace so test conversations don't show up next to the real WeChat sessions.
const env = {
  ...process.env,
  CLAUDE_WECHAT_STATE_DIR: stateDir,
  CLAUDE_WECHAT_CONFIG: configFile,
  CLAUDE_WECHAT_WORKSPACE: path.join(tmp, "workspace"),
};

const mockLines = [];
const bridgeLines = [];
const procs = [];
function start(name, args, sink) {
  const p = spawn(process.execPath, args, { cwd: ROOT, env, windowsHide: true });
  procs.push(p);
  const onData = (d) => {
    for (const line of d.toString("utf-8").split(/\r?\n/).filter(Boolean)) {
      sink.push(line);
      console.log(`${name}| ${line}`);
    }
  };
  p.stdout.on("data", onData);
  p.stderr.on("data", onData);
  return p;
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function waitFor(pred, ms, what) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    if (pred()) return;
    await sleep(500);
  }
  throw new Error(`timed out waiting for: ${what}`);
}
const sends = () => mockLines.filter((l) => l.startsWith("MOCK sendmessage"));
/** Wait for a new sendmessage (after index `from`) matching `pred`; returns it. */
async function waitSend(from, pred, ms, what) {
  let found;
  await waitFor(() => (found = sends().slice(from).find(pred)), ms, what);
  return found;
}
const inject = (text) => fetch(`http://127.0.0.1:${MOCK_PORT}/inject`, { method: "POST", body: JSON.stringify({ text }) });
function wake(args) {
  return new Promise((resolve) => {
    execFile(process.execPath, ["wake.js", ...args], { cwd: ROOT, env }, (err, stdout, stderr) => {
      console.log(`wake| ${(stdout + stderr).trim()}`);
      resolve(!err);
    });
  });
}
const ok = (msg) => console.log(`\n✔ ${msg}\n`);

let failed = false;
try {
  start("mock", ["test/mock-ilink.mjs", String(MOCK_PORT), "这是一条测试消息。请只回复两个字：你好"], mockLines);
  await waitFor(() => mockLines.some((l) => l.includes("listening")), 5000, "mock server");
  start("bridge", ["bridge.js"], bridgeLines);

  // 1. inbound message
  const first = await waitSend(0, () => true, 180_000, "reply to the first WeChat message");
  if (!first.includes("to=owner@im.wechat") || !first.includes("ctx=ctx-1") || !first.includes("type=2")) {
    throw new Error(`reply has wrong routing: ${first}`);
  }
  if (!mockLines.some((l) => l.includes("sendtyping status=1"))) throw new Error("no typing indicator sent");
  ok("step 1: inbound message answered by Claude, with typing indicator");

  // 2. proactive text
  let n = sends().length;
  if (!(await wake(["--send", "这是一条主动推送测试"]))) throw new Error("wake --send failed");
  await waitSend(n, (l) => l.includes("主动推送测试"), 15_000, "direct proactive send");
  ok("step 2: proactive send via wake.js --send");

  // 3. Claude-generated proactive message
  n = sends().length;
  if (!(await wake(["这是一次测试唤醒：请只回复「定时测试成功」这几个字。"]))) throw new Error("wake prompt failed");
  await waitSend(n, () => true, 180_000, "Claude-generated proactive message");
  ok("step 3: proactive message generated by Claude via wake.js");

  // 4. NO_MESSAGE
  n = sends().length;
  if (!(await wake(["这是一次测试唤醒：现在没有任何需要告诉用户的事。"]))) throw new Error("wake prompt 2 failed");
  await waitFor(() => bridgeLines.some((l) => l.includes("不需要打扰")), 180_000, "NO_MESSAGE handling");
  await sleep(2000);
  if (sends().length !== n) throw new Error("a message was sent even though Claude answered NO_MESSAGE");
  ok("step 4: NO_MESSAGE suppresses the proactive message");

  // 5. /effort
  n = sends().length;
  await inject("/effort low");
  await waitSend(n, (l) => l.includes("思考程度已调到：low"), 15_000, "reply to /effort command");
  n = sends().length;
  await inject("这是测试：只回复一个字：好");
  await waitSend(n, () => true, 180_000, "reply after changing effort");
  if (!bridgeLines.some((l) => l.includes("思考：low"))) throw new Error("effort was not passed to Claude");
  n = sends().length;
  await inject("/status");
  await waitSend(n, (l) => l.includes("思考程度：low"), 15_000, "reply to /status");
  ok("step 5: /effort switches thinking level, used on the next call and shown in /status");

  // 6. send an image from a script
  n = sends().length;
  if (!(await wake(["--file", pngFile]))) throw new Error("wake --file failed");
  await waitSend(n, (l) => l.includes("item=2 image") && l.includes("key=yes"), 15_000, "image message");
  if (!mockLines.some((l) => l.includes("MOCK cdn upload") && l.includes("md5match=true"))) throw new Error("uploaded image did not decrypt to the original");
  ok("step 6: wake.js --file uploads (encrypted, verified) and sends an image");

  // 7. Claude uses tools (progress shown) and sends a file back
  n = sends().length;
  const progressBefore = mockLines.filter((l) => l.startsWith("MOCK progress")).length;
  await inject(`请用命令列出这个文件夹里的文件：${filesDir} ，然后把其中的 note.txt 发给我。`);
  await waitSend(n, (l) => l.includes("item=4 file") && l.includes("note.txt"), 240_000, "file sent back by Claude");
  const progress = mockLines.filter((l) => l.startsWith("MOCK progress")).slice(progressBefore);
  if (!progress.some((l) => l.includes("start run=yes")) || !progress.some((l) => l.includes("end run=yes"))) {
    throw new Error("no tool progress items were shown");
  }
  ok(`step 7: tool progress shown (${progress.length} items) and Claude sent note.txt back`);

  // 8. /stop interrupts a long-running task
  n = sends().length;
  const logMark = bridgeLines.length;
  await inject("这是测试：请用 Bash 工具运行这条命令：powershell -NoProfile -Command \"Start-Sleep -Seconds 120\" ，等它结束后告诉我「完成」。");
  await waitFor(() => bridgeLines.slice(logMark).some((l) => l.includes("运行命令")), 120_000, "long command to start");
  await inject("/stop");
  await waitSend(n, (l) => l.includes("已停止当前任务"), 20_000, "/stop confirmation");
  await waitFor(() => bridgeLines.slice(logMark).some((l) => l.includes("任务已被 /stop 停止")), 20_000, "run aborted");
  await sleep(3000);
  if (sends().slice(n).some((l) => l.includes("完成"))) throw new Error("task kept going after /stop");
  ok("step 8: /stop interrupts a running task immediately");

  // 9. /screenshot
  if (!skipScreenshot) {
    n = sends().length;
    await inject("/screenshot");
    const r = await waitSend(n, (l) => l.includes("item=2 image") || l.includes("截图失败"), 60_000, "screenshot result");
    if (r.includes("截图失败")) throw new Error(`screenshot failed: ${r}`);
    ok("step 9: /screenshot captures the screen and sends it as an image");
  }

  const usage = fs.readFileSync(path.join(stateDir, "usage.jsonl"), "utf-8").trim().split("\n").map((l) => JSON.parse(l));
  console.log(`usage entries: ${usage.length}, list-price total $${usage.reduce((s, u) => s + (u.costUsd || 0), 0).toFixed(4)}`);
} catch (err) {
  failed = true;
  console.error(`\n✖ ${err.message}`);
} finally {
  for (const p of procs) p.kill();
  try {
    fs.rmSync(path.join(stateDir, "media"), { recursive: true, force: true }); // drop test screenshots
  } catch {
    /* ignore */
  }
  console.log(failed ? "E2E FAILED" : "E2E PASSED");
  process.exit(failed ? 1 : 0);
}
